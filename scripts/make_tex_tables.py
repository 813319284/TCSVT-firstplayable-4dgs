#!/usr/bin/env python3
"""make_tex_tables.py — 由产物直接生成论文用的 LaTeX 表格体。

输出（paper/tables/）：
  scenes.tex          Table I  场景、捕获方式、标定/评测帧数、16-bit 大小、码率构成
  sens.tex            Table II 单组 4-bit 截断损失（新网格、校准帧）
  firstplayable.tex   Table III 首次可播放字节（真实传输字节）
  scalable.tex        Table IV 单流 vs 按预算优化分配

每张表只写 tabular 体（不含 table 浮动体），main.tex 里 \\input 它们。
"""
from __future__ import annotations

import csv
import json
import os

def write_body(path, lines):
    """表体统一自带 \bottomrule：正文里不再写 \bottomrule，避免重复/缺失两种失败模式。"""
    body = [ln for ln in lines]
    while body and body[-1].strip() in (r"\midrule", r"\bottomrule"):
        body.pop()
    body.append(r"\bottomrule")
    open(path, "w").write("% generated by scripts/make_tex_tables.py\n" + "\n".join(body) + "\n")

W = os.environ.get("TCSVT_ROOT") or os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCENES = ["backpack", "sriracha", "truck", "umbrella", "jumping"]
NICE = {"backpack": r"\emph{backpack}", "sriracha": r"\emph{sriracha}",
        "truck": r"\emph{Truck}", "umbrella": r"\emph{Umbrella}", "jumping": r"\emph{Jumping}"}
GROUPS = [("b.means", "bg.means"), ("b.quats", "bg.quats"), ("b.scales", "bg.scales"),
          ("b.colors", "bg.colors"), ("b.opac.", "bg.opacities"),
          ("f.means", "fg.means"), ("f.quats", "fg.quats"), ("f.scales", "fg.scales"),
          ("f.colors", "fg.colors"), ("f.opac.", "fg.opacities"),
          ("m.coefs", "fg.motion_coefs")]


def main() -> int:
    os.makedirs(f"{W}/paper/tables", exist_ok=True)

    # ---------- Table I：场景 ----------
    rows = []
    for sc in SCENES:
        r = json.load(open(f"{W}/work/rates_{sc}.json"))
        comp = {k.replace(".params.", "."): v["16"] for k, v in r["components"].items()}
        tot = sum(comp.values()) + r["fixed_bytes"]
        bg = sum(v for k, v in comp.items() if k.startswith("bg."))
        mom = comp.get("fg.motion_coefs", 0) / tot * 100
        d = json.load(open(f"{W}/work/final/p0_{sc}.json"))
        rows.append((sc, tot / 1e6, bg / tot * 100, mom, len(d["calib_ids"]), len(d["eval_ids"])))
    body = []
    for sc, tot, bg, mom, nc, ne in rows:
        cap = "handheld" if sc in ("backpack", "sriracha") else "multi-view"
        ev = f"{ne}" if sc in ("backpack", "sriracha") else f"{ne}"
        body.append(f"{NICE[sc]} & {cap} & {nc} & {ev} & {tot:.2f} & {bg:.1f}\\% & {mom:.1f}\\%\\\\")
    write_body(f"{W}/paper/tables/scenes.tex", body)
    print("scenes.tex", len(body), "rows")

    # ---------- Table II：单组灵敏度 ----------
    sens = {sc: json.load(open(f"{W}/work/sens_p0_{sc}.json"))["groups"] for sc in SCENES}
    body = []
    for nice, key in GROUPS:
        cells = [f"{sens[sc][key]['loss_full']:.2f}" for sc in SCENES]
        body.append(f"{nice} & " + " & ".join(cells) + r"\\")
    write_body(f"{W}/paper/tables/sens.tex", body)
    print("sens.tex", len(body), "rows")

    # ---------- Table III：首次可播放 ----------
    body = []
    for r in csv.DictReader(open(f"{W}/reports/table_firstplayable.csv")):
        sc = r["scene"]
        best = r["best_fixed_order"].replace("mpprefix", "m.p.").replace("roundrobin", "r.r.") \
                                    .replace("oneshot", "frozen").replace("sens", "sens.")
        body.append(f"{NICE[sc]} & {float(r['base_MB']):.2f} & {float(r['uniform_MB']):.2f} & "
                    f"{float(r['best_fixed_MB']):.2f} ({best}) & \\textbf{{{float(r['direct_MB']):.2f}}} & "
                    f"{float(r['save_vs_best_pct']):.1f}\\%\\\\")
    write_body(f"{W}/paper/tables/firstplayable.tex", body)
    print("firstplayable.tex", len(body), "rows")

    # ---------- Table IV：单流 vs 按预算分配 ----------
    body, seen = [], set()
    for sc in SCENES:
        p = f"{W}/work/final/p0_alloc_{sc}.json"
        if not os.path.exists(p):
            continue
        al = json.load(open(p))
        st = json.load(open(f"{W}/work/final/p0_{sc}.json"))
        direct = [r for r in st["results"] if r["order"] == "direct"]
        first = True
        for b in al["budgets"]:
            B = b["bytes"]
            key = (sc, round(B / 1e6, 2))
            if key in seen:
                continue
            seen.add(key)
            cand = [r for r in direct if r["bytes"] <= B]
            s = cand[-1] if cand else None
            if s is None:
                continue
            df = s["psnr_first"] - b["eval_full"]
            dg = s["psnr_first_fg"] - b["eval_fg"]
            name = NICE[sc] if first else ""
            first = False
            body.append(f"{name} & {B / 1e6:.2f} & {b['eval_full']:.2f} & {s['psnr_first']:.2f} & "
                        f"${df:+.2f}$ & {b['eval_fg']:.2f} & {s['psnr_first_fg']:.2f} & ${dg:+.2f}$\\\\")
        body.append(r"\midrule" if sc != SCENES[-1] else r"\bottomrule")
    write_body(f"{W}/paper/tables/scalable.tex", body)
    print("scalable.tex", len(body), "lines")

    # ---------- Table VI：逐包重估的强自适应基线（逐包重估强基线）----------
    fixed_orders = ["uniform", "roundrobin", "posfirst", "dynfirst", "oneshot", "mpprefix"]

    def fp(path):
        d = json.load(open(path))
        v = d["summary"]["direct"]["bytes_to_ref_minus_0.5"]
        return None if v is None else v / 1e6

    body = []
    for sc in SCENES:
        b = json.load(open(f"{W}/work/final/p0_{sc}.json"))
        best = min(b["summary"][k]["bytes_to_ref_minus_0.5"] for k in fixed_orders) / 1e6
        ours = b["summary"]["direct"]["bytes_to_ref_minus_0.5"] / 1e6
        fg = fp(f"{W}/work/final/adaptive_full_gain_{sc}.json")
        jg = fp(f"{W}/work/final/adaptive_joint_gain_{sc}.json")
        fmt = lambda v: "not reached" if v is None else f"{v:.2f}"
        # 加粗规则：每行最小值加粗（并列同时加粗），不对 Ours 单独加粗
        cells = [("best", best), ("fg", fg), ("jg", jg), ("ours", ours)]
        nums = [v for k, v in cells if v is not None]
        lo = min(nums)
        rendered = []
        for k, v in cells:
            txt = fmt(v)
            if v is not None and abs(v - lo) < 1e-9:
                txt = f"\\textbf{{{txt}}}"
            rendered.append(txt)
        body.append(f"{NICE[sc]} & " + " & ".join(rendered) + r"\\")
    write_body(f"{W}/paper/tables/adaptive.tex", body)
    print("adaptive.tex", len(body), "rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
